import React, { useRef } from 'react';
import { FEATURE_LABELS, REVERSE_MAPPING } from '../utils/prediction';
import GaugeChart from './GaugeChart';
import html2pdf from 'html2pdf.js';

const ALL_FEATURES = ['age', 'sex', 'cp', 'trestbps', 'chol', 'fbs', 'restecg', 'thalach', 'exang', 'oldpeak', 'slope', 'ca', 'thal'];
const HOME_PAGE_FEATURES = ['age', 'sex', 'cp', 'trestbps', 'chol', 'fbs', 'thalach', 'exang', 'oldpeak', 'thal'];

function PredictionSection({ prediction, probability, inputData, riskFactors, protectiveFactors, onExplain, onBack }) {
  const contentRef = useRef();

  const handleDownloadPDF = () => {
    // Dynamically import jsPDF to avoid issues
    import('jspdf').then((jsPDF) => {
      const doc = new jsPDF.default();
      
      // Add title
      doc.setFontSize(18);
      doc.text('Quantum Heart Disease Prediction', 105, 10, null, null, 'center');
      
      doc.setFontSize(14);
      doc.text('AI-Powered Cardiovascular Risk Assessment Report', 105, 20, null, null, 'center');
      
      // Add generation date
      doc.setFontSize(12);
      const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
      const timeStr = new Date().toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });
      doc.text(`Generated on: ${dateStr} at ${timeStr}`, 105, 30, null, null, 'center');
      
      // Add risk assessment summary
      doc.setFontSize(14);
      doc.text('Risk Assessment Summary', 20, 45);
      
      doc.setFontSize(12);
      const isHighRisk = prediction === 1;
      const probabilityText = (probability * 100).toFixed(2) + '%';
      const riskLevel = isHighRisk ? 'High Risk' : 'Low Risk';
      
      doc.text(`Risk Level: ${riskLevel}`, 20, 55);
      doc.text(`Risk Probability: ${probabilityText}`, 20, 65);
      doc.text('Prediction Model: Ensemble Quantum Support Vector Classification (QSVC) Model', 20, 75);
      
      // Add patient information
      doc.setFontSize(14);
      doc.text('Patient Clinical Information', 20, 90);
      
      doc.setFontSize(10);
      let yPosition = 100;
      HOME_PAGE_FEATURES.forEach(feat => {
        if (inputData && feat in inputData) {
          let val = inputData[feat];
          if (REVERSE_MAPPING[feat] && REVERSE_MAPPING[feat][val] !== undefined) {
            val = REVERSE_MAPPING[feat][val];
          }
          const featureText = `${FEATURE_LABELS[feat]}: ${val}`;
          
          // Check if we need a new page
          if (yPosition > 270) {
            doc.addPage();
            yPosition = 20;
          }
          
          doc.text(featureText, 20, yPosition);
          yPosition += 6;
        }
      });
      
      // Add risk factors if available
      if (riskFactors && riskFactors.length > 0) {
        doc.setFontSize(14);
        doc.text('KEY RISK FACTORS', 20, yPosition);
        yPosition += 10;
        
        doc.setFontSize(10);
        riskFactors.slice(0, 5).forEach(factor => {
          if (yPosition > 270) {
            doc.addPage();
            yPosition = 20;
          }
          doc.text(`• ${factor.text} - ${factor.detail}`, 20, yPosition);
          yPosition += 6;
        });
      }
      
      // Add protective factors if available
      if (protectiveFactors && protectiveFactors.length > 0) {
        doc.setFontSize(14);
        doc.text('PROTECTIVE FACTORS', 20, yPosition);
        yPosition += 10;
        
        doc.setFontSize(10);
        protectiveFactors.slice(0, 5).forEach(factor => {
          if (yPosition > 270) {
            doc.addPage();
            yPosition = 20;
          }
          doc.text(`• ${factor.text} - ${factor.detail}`, 20, yPosition);
          yPosition += 6;
        });
      }
      
      // Add disclaimer
      if (yPosition > 270) {
        doc.addPage();
        yPosition = 20;
      }
      
      doc.setFontSize(14);
      doc.setTextColor(255, 0, 0); // Red text
      doc.text('MEDICAL DISCLAIMER', 20, yPosition);
      yPosition += 8;
      
      doc.setFontSize(10);
      doc.setTextColor(0, 0, 0); // Black text
      
      // Split disclaimer text into lines that fit the page
      const disclaimerText = 'This report is generated by an artificial intelligence prediction model and is intended for informational purposes only. It is NOT a substitute for professional medical advice, diagnosis, or treatment. Always consult with qualified healthcare providers for medical decisions.';
      
      const maxWidth = 170; // Maximum width for text
      const lines = doc.splitTextToSize(disclaimerText, maxWidth);
      
      lines.forEach(line => {
        if (yPosition > 270) {
          doc.addPage();
          yPosition = 20;
        }
        doc.text(line, 20, yPosition);
        yPosition += 6;
      });
      
      // Save the PDF
      doc.save(`Heart_Risk_Prediction_Report_${new Date().toISOString().slice(0, 10)}.pdf`);
    }).catch(err => {
      console.error('Error importing jsPDF:', err);
      // Fallback to text file if jsPDF fails
      alert('PDF generation failed. Please try again or contact support.');
    });
  };

  if (prediction === null || probability === null) {
    return (
      <section className="fade-in">
        <div className="page-header">
          <h1 className="page-title">
            <i className="fas fa-chart-pie" style={{ color: 'var(--accent-secondary)' }}></i>
            Prediction Result
          </h1>
          <p className="breadcrumb">
            <i className="fas fa-home"></i> Home <i className="fas fa-chevron-right"></i> Prediction Result
          </p>
        </div>

        <div className="card" style={{ textAlign: 'center', padding: '60px' }}>
          <i className="fas fa-clipboard-list" style={{ fontSize: '64px', color: 'var(--text-secondary)', marginBottom: '20px' }}></i>
          <p style={{ color: 'var(--text-secondary)', fontSize: '16px', marginBottom: '24px' }}>
            No prediction available. Please go to Home and submit patient information first.
          </p>
          <button className="btn btn-primary" onClick={onBack}>
            <i className="fas fa-arrow-left"></i> Go to Home
          </button>
        </div>
      </section>
    );
  }

  const isHighRisk = prediction === 1;
  const riskClass = isHighRisk ? 'risk-high' : 'risk-low';
  const riskText = isHighRisk ?
    <><i className="fas fa-triangle-exclamation"></i> High Risk Detected</> :
    <><i className="fas fa-check-circle"></i> Low Risk</>;
  const cardClass = isHighRisk ? '' : 'low-risk';

  return (
    <section className="fade-in" ref={contentRef}>
      <div className="page-header">
        <h1 className="page-title">
          <i className="fas fa-chart-pie" style={{ color: 'var(--accent-secondary)' }}></i>
          Prediction Result
        </h1>
        <p className="breadcrumb">
          <i className="fas fa-home"></i> Home <i className="fas fa-chevron-right"></i> Prediction Result
        </p>
      </div>

      <div className="stats-grid">
        <div className="stat-card">
          <div className="stat-value">{(probability * 100).toFixed(0)}%</div>
          <div className="stat-label">Risk Probability</div>
        </div>
        <div className="stat-card">
          <div className="stat-value">{isHighRisk ? 'High' : 'Low'}</div>
          <div className="stat-label">Risk Level</div>
        </div>
        <div className="stat-card">
          <div className="stat-value">QSVC</div>
          <div className="stat-label">Model</div>
        </div>
      </div>

      <div className="card">
        <h2 className="card-title">
          <i className="fas fa-clipboard-list"></i>
          Patient Information Summary
        </h2>
        <table>
          <thead>
            <tr>
              <th>Feature</th>
              <th>Value</th>
            </tr>
          </thead>
          <tbody>
            {HOME_PAGE_FEATURES.map(feat => {
              if (inputData && feat in inputData) {
                let val = inputData[feat];
                if (REVERSE_MAPPING[feat] && REVERSE_MAPPING[feat][val] !== undefined) {
                  val = REVERSE_MAPPING[feat][val];
                }
                return (
                  <tr key={feat}>
                    <td>{FEATURE_LABELS[feat]}</td>
                    <td>{val}</td>
                  </tr>
                );
              }
              return null;
            })}
          </tbody>
        </table>
      </div>

      <div className={`result-card ${cardClass}`}>
        <div style={{ fontSize: '12px', color: 'var(--text-secondary)', textTransform: 'uppercase', letterSpacing: '1px', marginBottom: '12px' }}>
          Prediction Result
        </div>
        <div className={`risk-title ${riskClass}`}>{riskText}</div>

        <div className="gauge-container">
          <GaugeChart value={probability} isHighRisk={isHighRisk} />
        </div>

        <div className="probability-section">
          <div style={{ fontSize: '14px', color: 'var(--text-secondary)', marginBottom: '8px' }}>
            Risk Probability: <span style={{ fontSize: '24px', fontWeight: 700, color: isHighRisk ? 'var(--danger)' : 'var(--success)' }}>{(probability * 100).toFixed(0)}%</span>
          </div>
          <div className="probability-bar">
            <div className="probability-marker" style={{ left: `${probability * 100}%` }}>{(probability * 100).toFixed(0)}%</div>
          </div>
          <div className="probability-labels">
            <span>0%</span><span>25%</span><span>50%</span><span>75%</span><span>100%</span>
          </div>
        </div>
        <div className="model-badge">
          <i className="fas fa-microchip"></i>
          Ensemble Quantum QSVC Model
        </div>

        {riskFactors.length > 0 && (
          <div className="risk-factors">
            <div className="risk-factors-title">
              <i className="fas fa-triangle-exclamation"></i>
              Key Risk Factors
            </div>
            {riskFactors.map((rf, idx) => (
              <div key={idx} className="risk-factor-item">
                <i className={`fas ${rf.icon}`}></i>
                <div>
                  <div style={{ fontWeight: 500 }}>{rf.text}</div>
                  <div style={{ fontSize: '12px', opacity: 0.8 }}>{rf.detail}</div>
                </div>
              </div>
            ))}
          </div>
        )}

        {protectiveFactors.length > 0 && (
          <div className="protective-factors">
            <div className="protective-factors-title">
              <i className="fas fa-shield-heart"></i>
              Protective Factors
            </div>
            {protectiveFactors.map((pf, idx) => (
              <div key={idx} className="protective-factor-item">
                <i className={`fas ${pf.icon}`}></i>
                <div>
                  <div style={{ fontWeight: 500 }}>{pf.text}</div>
                  <div style={{ fontSize: '12px', opacity: 0.8 }}>{pf.detail}</div>
                </div>
              </div>
            ))}
          </div>
        )}

        <div className="pdf-hide-buttons" style={{ display: 'flex', gap: '16px', marginTop: '24px' }}>
          <button className="btn btn-primary" onClick={onExplain} style={{ flex: 1 }}>
            <i className="fas fa-microscope"></i> Explain Prediction
          </button>
          <button className="btn btn-outline" onClick={handleDownloadPDF} style={{ flex: 1, borderColor: 'var(--accent-secondary)', color: 'var(--accent-secondary)' }}>
            <i className="fas fa-file-pdf"></i> Download PDF
          </button>
        </div>
      </div>
    </section>
  );
}

export default PredictionSection;